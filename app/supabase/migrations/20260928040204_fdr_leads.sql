create table public.enquiry_tests (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    channel text not null check (channel in ('web_form','phone','email','chat','whatsapp','marketplace','other')),
    what_sent text not null,
    sent_at timestamptz not null,
    replied_at timestamptz,
    reply_summary text,
    observed text,
    sales_id bigint references public.sales(id),
    created_at timestamptz not null default now()
);
create table public.call_logs (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    contact_id bigint references public.contacts(id) on delete set null,
    outcome text not null check (outcome in ('no_answer','voicemail','gatekeeper','spoke_owner','booked','not_interested','wrong_number')),
    note text,
    called_at timestamptz not null default now(),
    sales_id bigint references public.sales(id)
);
create table public.whatsapp_opens (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    opened_at timestamptz not null default now(),
    sales_id bigint references public.sales(id)
);
create index enquiry_tests_company_id_idx on public.enquiry_tests(company_id);
