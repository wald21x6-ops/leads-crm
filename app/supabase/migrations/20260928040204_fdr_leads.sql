create or replace view public.companies_summary with (security_invoker = on) as
select
    c.id,
    c.created_at,
    c.name,
    c.sector,
    c.size,
    c.linkedin_url,
    c.website,
    c.phone_number,
    c.address,
    c.zipcode,
    c.city,
    c.state_abbr,
    c.sales_id,
    c.context_links,
    c.country,
    c.description,
    c.revenue,
    c.tax_identifier,
    c.logo,
    count(distinct d.id) as nb_deals,
    count(distinct co.id) as nb_contacts,
    c.external_key, c.research_status, c.research, c.first_line,
    c.score, c.timezone, c.source, c.business_type
from public.companies c
    left join public.deals d on c.id = d.company_id
    left join public.contacts co on c.id = co.company_id
group by c.id;


-- Precedence is overdue, stale, no next step; recently created deals cannot be stale.
create or replace view public.deal_health with (security_invoker = on) as
select h.*, case
    when h.stage in ('won','lost') then 'ok'
    when h.next_task_due < now() then 'overdue'
    when h.created_at < now() - interval '7 days'
      and h.last_touch_at < now() - interval '7 days' then 'stale'
    when h.open_task_count = 0 then 'no_next_step'
    else 'ok'
end as state
from (
    select d.id, d.company_id, d.stage, d.created_at,
      greatest(d.updated_at, d.created_at,
        (select max(n.date) from public.deal_notes n where n.deal_id = d.id),
        (select max(n.date) from public.contact_notes n join public.contacts c on c.id = n.contact_id where c.company_id = d.company_id),
        (select max(l.called_at) from public.call_logs l where l.company_id = d.company_id),
        (select max(w.opened_at) from public.whatsapp_opens w where w.company_id = d.company_id),
        (select max(greatest(e.sent_at, e.replied_at)) from public.enquiry_tests e where e.company_id = d.company_id),
        (select max(t.done_date) from public.tasks t join public.contacts c on c.id = t.contact_id where c.company_id = d.company_id)
      ) as last_touch_at,
      (select min(t.due_date) from public.tasks t join public.contacts c on c.id = t.contact_id where c.company_id = d.company_id and t.done_date is null) as next_task_due,
      (select count(*) from public.tasks t join public.contacts c on c.id = t.contact_id where c.company_id = d.company_id and t.done_date is null) as open_task_count
    from public.deals d
) h;

